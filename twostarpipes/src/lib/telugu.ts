export function translate(
  language: "en" | "te",
  text: string,
  values: Record<string, string | number> = {},
) {
  const key = text.replace(/\s+/g, " ").trim();
  let result = language === "te" ? (TELUGU[key] ?? key) : key;
  if (language === "te" && !TELUGU[key]) {
    if (/^Celebrating \d+ Years · /.test(key))
      result = `${key.match(/\d+/)?.[0]} ఏళ్ల వేడుక · ${TELUGU["Be a Star, Be with Star"]}`;
    else if (/^\d+th Years of Excellence$/.test(key))
      result = `${key.match(/\d+/)?.[0]} ఏళ్ల నాణ్యమైన సేవలు`;
    else if (/^Show slide \d+$/.test(key)) result = `స్లైడ్ ${key.match(/\d+/)?.[0]} చూపించండి`;
    else if (/^Too big:/.test(key)) result = "అనుమతించిన పరిమితి కంటే ఎక్కువ అక్షరాలు ఉన్నాయి.";
    else if (/^(Invalid input|Invalid option|Too small:)/.test(key))
      result = "దయచేసి సరైన వివరాలు నమోదు చేయండి.";
    else if (/^\d+ mm$/.test(key)) result = key.replace(" mm", " మి.మీ.");
    else if (/inch/.test(key)) result = key.replace("inch", "అంగుళాలు");
  }
  result = result.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
  return (text.match(/^\s*/)?.[0] ?? "") + result + (text.match(/\s*$/)?.[0] ?? "");
}
